#!/usr/bin/env python3
"""Turn the most repeated inline style attributes into shared utility classes.
Same look: the classes use !important so they win over other rules exactly as inline styles did.
Usage: python tools/inline_to_classes.py [min_count]   (default 10). Run tools/check.mjs --shots before and after and diff."""
import re, sys, collections, os
root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
p = os.path.join(root, "index.html")
MIN = int(sys.argv[1]) if len(sys.argv) > 1 else 10
t = open(p, "rb").read().decode("utf-8")
nl = "\r\n" if "\r\n" in t[:5000] else "\n"

# split into markup and script/style regions: only markup is touched
parts = re.split(r"(<script\b[\s\S]*?</script>|<style\b[\s\S]*?</style>)", t)
cnt = collections.Counter()
tagre = re.compile(r"<([a-z][a-z0-9]*)\b([^<>]*?)>")
def key(tag, attrs):
    m = re.search(r'\sstyle="([^"]+)"', " " + attrs)
    return (tag, m.group(1)) if m else None
for i in range(0, len(parts), 2):
    for m in tagre.finditer(parts[i]):
        k = key(m.group(1), m.group(2))
        if k and not m.group(2).lstrip().startswith("/"): cnt[k] += 1
chosen = [k for k, n in cnt.most_common() if n >= MIN]
names = {k: "u%02d" % (i + 1) for i, k in enumerate(chosen)}

def norm(style):
    s = style.strip()
    return s if s.endswith(";") else s + ";"

def rewrite(m):
    tag, attrs = m.group(1), m.group(2)
    k = key(tag, attrs)
    if not k or k not in names: return m.group(0)
    cls = names[k]
    a = re.sub(r'\sstyle="[^"]+"', "", " " + attrs, count=1)[1:] if attrs.startswith(" ") else re.sub(r'\sstyle="[^"]+"', "", " " + attrs, count=1)
    cm = re.search(r'\sclass="([^"]*)"', " " + a)
    if cm:
        a = re.sub(r'class="([^"]*)"', lambda x: 'class="' + x.group(1) + " " + cls + '"', a, count=1)
    else:
        a = a.rstrip()
        a = (a + " " if a else " ") + 'class="' + cls + '"'
        if not a.startswith(" "): a = " " + a
    return "<" + tag + (a if a.startswith(" ") else " " + a) + ">"

out = []
for i, part in enumerate(parts):
    out.append(part if i % 2 else tagre.sub(rewrite, part))
t2 = "".join(out)

css = ["      /* Shared utility classes generated by tools/inline_to_classes.py from repeated inline styles. !important keeps the exact precedence inline styles had. */"]
for (tag, st), nme in names.items():
    css.append("      .%s{%s}" % (nme, norm(st).replace(";", " !important;").replace("  ", " ")))
anchor = "      .more-text .more-body > * + *{margin-top:14px;}"
assert t2.count(anchor) == 1
t2 = t2.replace(anchor, anchor + nl + nl.join(css))
open(p, "wb").write(t2.encode("utf-8"))
before = sum(cnt.values()); after = len(re.findall(r'<[a-z][^<>]*\sstyle="', "".join(p_ for i, p_ in enumerate(out) if i % 2 == 0)))
print("classes", len(names), "inline styles", before, "->", after)
