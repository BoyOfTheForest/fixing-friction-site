#!/usr/bin/env python3
"""Copy consistency report (report only, edits nothing). Writes docs/COPY-REPORT.md.
Finds repeated words, spacing before punctuation, missing space after a full stop, mixed quote styles,
label spelling variants, and lists every price and date with its page, so mismatches are easy to spot."""
import re, os, collections, html
root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
t = open(os.path.join(root, "index.html"), "rb").read().decode("utf-8")
main = t[t.index("<main"):t.index("</main>")] if "<main" in t else t
main = re.sub(r"<(script|style)\b[\s\S]*?</\1>", " ", main)
secs = re.split(r'(?=<section class="page(?: active)?" id="page-)', main)
rows = []
for s in secs:
    m = re.match(r'<section class="page(?: active)?" id="page-([a-z0-9-]+)"', s)
    if not m: continue
    txt = re.sub(r"</?(?:a|strong|em|span|b|i|small|code|sup|sub|mark|abbr|u)[^>]*>", "", s)
    txt = html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " | ", txt)))
    rows.append((m.group(1), txt))
out = ["# Copy consistency report", "", "Generated by tools/copy_report.py. Report only: nothing was changed. Review each line and decide.", ""]
def add(title, items, limit=60):
    out.append("## %s (%d)" % (title, len(items))); out.append("")
    if not items: out.append("None found."); out.append("")
    for i in items[:limit]: out.append("- " + i)
    if len(items) > limit: out.append("- ... %d more" % (len(items) - limit))
    out.append("")
rep, sp, nosp, quotes = [], [], [], []
for pid, txt in rows:
    for m in re.finditer(r"\b([A-Za-z]{2,})\s+\1\b", txt):
        if m.group(1).lower() not in ("that", "had") : rep.append("%s: \"%s\"" % (pid, txt[max(0, m.start() - 25):m.end() + 25])) if "|" not in m.group(0) else None
    for m in re.finditer(r"\w \s?[,.;:!?](?=\s|$)", txt):
        sp.append("%s: \"%s\"" % (pid, txt[max(0, m.start() - 25):m.end() + 15]))
    for m in re.finditer(r"[a-z]{3,}[.!?][A-Z][a-z]{2,}", txt):
        if not re.search(r"\.(com|org|net|js)", m.group(0)): nosp.append("%s: \"%s\"" % (pid, txt[max(0, m.start() - 20):m.end() + 20]))
    st, cu = len(re.findall(r"\w'\w", txt)), len(re.findall("’", txt))
    if st and cu: quotes.append("%s: %d straight and %d curly apostrophes" % (pid, st, cu))
add("Repeated words", rep); add("Space before punctuation", sp); add("Missing space after a full stop", nosp); add("Mixed apostrophe styles on one page", quotes)

alltxt = " ".join(x for _, x in rows)
variants = {
 "Scorecard": r"\b[Ss]corecard\b", "Accessibility Friction": r"\b[Aa]ccessibility [Ff]riction\b", "ADA Coordinator": r"\b(?:ADA [Cc]oordinator|ADAC)\b",
 "Surface Audit": r"\b[Ss]urface [Aa]udit\b", "Accessibility Assessment": r"\b[Aa]ccessibility [Aa]ssessment\b", "Full Accessibility Audit": r"\b[Ff]ull [Aa]ccessibility [Aa]udit\b",
 "Snapshot": r"\b[Ss]napshot\b", "Q1 pilot session": r"\bQ1 [Pp]ilot [Ss]ession\b", "Brain Blame": r"\b[Bb]rain [Bb]lame\b", "CareCircle": r"\b[Cc]are ?[Cc]ircle\b",
}
vitems = []
for name, rx in variants.items():
    c = collections.Counter(m.group(0) for m in re.finditer(rx, alltxt))
    if len(c) > 1: vitems.append("%s: %s" % (name, ", ".join("\"%s\" x%d" % (k, v) for k, v in c.most_common())))
add("Spelling and capitalisation variants (some are fine, for example a sentence start)", vitems)

prices = collections.defaultdict(list)
for pid, txt in rows:
    for m in re.finditer(r"\$[\d,]+(?:\.\d+)?(?:\s?[MK]\+?)?", txt):
        prices[m.group(0)].append("%s: \"%s\"" % (pid, txt[max(0, m.start() - 45):m.end() + 25]))
out.append("## Every price and dollar figure, with its page (%d distinct)" % len(prices)); out.append("")
out.append("Check that the same service always shows the same price.")
out.append("")
for k in sorted(prices, key=lambda x: float(re.sub(r"[^\d.]", "", x) or 0)):
    out.append("### " + k + " (x%d)" % len(prices[k]))
    for i in prices[k][:4]: out.append("- " + i)
    out.append("")
dates = collections.defaultdict(set)
for pid, txt in rows:
    for m in re.finditer(r"\b(?:January|February|March|April|May|June|July|August|September|October|November|December) \d{1,2}(?:, 20\d\d)?", txt):
        dates[m.group(0)].add(pid)
out.append("## Every date mentioned (%d distinct)" % len(dates)); out.append("")
for k in sorted(dates): out.append("- %s: %s" % (k, ", ".join(sorted(dates[k]))))
out.append("")
dash = sum(alltxt.count(x) for x in ("—", "–"))
out.append("## Other")
out.append("")
out.append("- Em or en dashes in visible text: %d" % dash)
out.append("- Email addresses in visible text: %s" % ", ".join(sorted(set(re.findall(r"[\w.+-]+@[\w-]+\.[\w.]+", alltxt)))))
open(os.path.join(root, "docs", "COPY-REPORT.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("report written;", len(rep), "repeats,", len(sp), "space-before-punct,", len(nosp), "missing-space,", len(prices), "prices")
